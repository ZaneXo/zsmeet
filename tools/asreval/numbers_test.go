package main

import "testing"

func TestSpokenNumbers(t *testing.T) {
	for in, want := range map[string]string{
		"十八到35岁":      "十八到三十五岁",
		"下午3点":        "下午三点",
		"3:30开会":      "三点三十开会",
		"9:00开会":      "九点开会",
		"增长了12.5%":    "增长了百分之十二点五",
		"2025年的预算":    "二零二五年的预算",
		"一共105个":      "一共一百零五个",
		"30000块":      "三万块",
		"1200人":       "一千二百人",
		"10086":       "一万零八十六",
		"13800138000": "一三八零零一三八零零零",
		"编号007":       "编号零零七",
		"1001":        "一千零一",
		"版本3.0":       "版本三点零",
		"没有数字":        "没有数字",
		"第10个和第20个":   "第十个和第二十个",
		"120万":        "一百二十万",
	} {
		if got := spokenNumbers(in); got != want {
			t.Errorf("spokenNumbers(%q) = %q, want %q", in, got, want)
		}
	}
}
